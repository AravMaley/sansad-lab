// Writes the public part of the topic list (no matching rules) for the
// front end:  node scripts/build-topics.mjs
import { writeFile } from "node:fs/promises";
import { TOPICS } from "./ingest/topics.js";

const pub = TOPICS.map(({ slug, label, blurb, ministries, keywords }) => ({
  slug, label, blurb, ministries, keywords: keywords.source,
}));
await writeFile(
  new URL("../web/js/topics-data.js", import.meta.url),
  `// Generated by scripts/build-topics.mjs. Do not edit.\nexport const TOPICS = ${JSON.stringify(pub, null, 2)};\n`,
);
console.log(`Wrote web/js/topics-data.js (${pub.length} topics)`);
